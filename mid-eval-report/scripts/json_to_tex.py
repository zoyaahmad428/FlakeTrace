"""Turn the real pipeline reports in eval/reports/*.json into LaTeX tables for the Mid report.

Why: every number in the report's results tables must trace to a real run. Typing numbers by
hand into .tex breaks that link; this script reads the committed reports and writes the table,
so re-running the pipeline and this script keeps the report in step.

Reads only (never writes) eval/reports/. Writes mid-eval-report/tables/generated/.

Run from the repository root:
    python3 mid-eval-report/scripts/json_to_tex.py
"""
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
REPORTS = REPO / "eval" / "reports"
OUT = REPO / "mid-eval-report" / "tables" / "generated"

CASES = ["f1", "f2", "f3", "f4", "n1", "n2", "n3"]


def tex(s):
    """Escape the characters LaTeX treats specially."""
    s = str(s)
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"),
                 ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"),
                 ("^", r"\textasciicircum{}")]:
        s = s.replace(a, b)
    return s


def short(test):
    """odfixture.ConfigVictimTest#expectsDefaultMode -> ConfigVictimTest."""
    if not test:
        return "--"
    return test["class"].rsplit(".", 1)[-1]


def breakable(s):
    """Let long CamelCase names and SNAKE_CASE reasons wrap inside narrow table cells."""
    s = re.sub(r"(?<=[a-z])(?=[A-Z])", r"\\allowbreak{}", s)
    return s.replace(r"\_", r"\_\allowbreak{}")


def rate(block):
    if not block:
        return "--"
    return f"{block['successes']}/{block['n']}"


def interval(block):
    if not block or block.get("lower") is None:
        return "--"
    return f"{block['lower']:.2f}--{block['upper']:.2f}"


def outcome(d):
    o = d.get("outcome", "?")
    r = d.get("unresolved_reason")
    return f"{o} ({r})" if r else o


def resource(d):
    r = d.get("shared_resource")
    if not r:
        return "--"
    if r.get("key"):  # system property, environment variable, file path ...
        name = r["key"]
    else:             # static field
        name = f"{r.get('class', '').rsplit('.', 1)[-1]}.{r.get('field', '')}".strip(".")
    return f"{r.get('kind', '')}: {name}"


def main():
    rows = []
    for case in CASES:
        path = REPORTS / f"{case}.json"
        if not path.exists():
            sys.exit(f"missing {path} - refusing to write a table with a hole in it")
        d = json.loads(path.read_text(encoding="utf-8"))
        orig = len(d.get("original_failing_order") or [])
        red = len(d.get("reduced_sequence") or [])
        cells = [breakable(tex(x)) for x in [
            case.upper(),
            short(d.get("victim")),
            outcome(d),
            rate(d.get("reproduction")),
            interval(d.get("reproduction")),
            rate(d.get("victim_alone")),
            len(d.get("polluters") or []),
        ]]
        cells.append(f"{orig} $\\to$ {red}" if orig else "--")  # LaTeX on purpose, not escaped
        cells.append(breakable(tex(resource(d))))
        rows.append(" & ".join(cells) + r" \\")

    OUT.mkdir(parents=True, exist_ok=True)
    body = "\n".join(rows)
    table = rf"""% GENERATED by mid-eval-report/scripts/json_to_tex.py from eval/reports/*.json - do not edit by hand.
{{\footnotesize\setlength{{\tabcolsep}}{{3pt}}
\begin{{longtable}}{{>{{\raggedright\arraybackslash}}p{{0.04\textwidth}}>{{\raggedright\arraybackslash}}p{{0.18\textwidth}}>{{\raggedright\arraybackslash}}p{{0.16\textwidth}}p{{0.05\textwidth}}p{{0.1\textwidth}}p{{0.05\textwidth}}p{{0.04\textwidth}}p{{0.06\textwidth}}>{{\raggedright\arraybackslash}}p{{0.16\textwidth}}}}
\caption{{Real diagnosis outcomes on the seeded fixture suite (20 replays per check, 95\% Wilson intervals)}}\label{{ch8:tab:fixture-results}}\\
\toprule
Case & Victim & Outcome & Repro. & Wilson 95\% & Alone fail & Poll. & Order & Shared resource\\
\midrule
\endfirsthead
\toprule
Case & Victim & Outcome & Repro. & Wilson 95\% & Alone fail & Poll. & Order & Shared resource\\
\midrule
\endhead
{body}
\bottomrule
\end{{longtable}}
}}
"""
    (OUT / "fixture_results.tex").write_text(table, encoding="utf-8")
    print(f"wrote {OUT / 'fixture_results.tex'} ({len(rows)} cases)")


if __name__ == "__main__":
    main()
